import { spawnSync } from 'node:child_process';
import { mkdir, access } from 'node:fs/promises';
import path from 'node:path';
if (process.platform !== 'win32') throw new Error('Windows is required to build the window reader');
const framework = path.join(process.env.WINDIR || 'C:/Windows', 'Microsoft.NET/Framework64/v4.0.30319');
const compiler = path.join(framework, 'csc.exe');
await access(compiler);
await mkdir('dist/native', { recursive: true });
const result = spawnSync(compiler, ['/nologo', '/target:exe', '/platform:x64', '/optimize+', `/out:${path.resolve('dist/native/foreground-reader.exe')}`, `/reference:${path.join(framework, 'System.Web.Extensions.dll')}`, path.resolve('native/ForegroundReader.cs')], { stdio: 'inherit', shell: false, windowsHide: true });
if (result.status !== 0) throw new Error('Window reader compilation failed');
